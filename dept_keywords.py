def count_symptom_coverage(patient_input: PatientInput):
    
    symptoms = [patient_input.symptom or ""]
    symptoms += patient_input.accompanying_symptoms or []
    symptoms = [s for s in symptoms if s]   
    total = len(symptoms) or 1              

    coverage_count = {}
    for dept, keywords in KEYWORD_TO_DEPT.items():
        matched = sum(
            1 for s in symptoms
            if any(kw in s or s in kw for kw in keywords)
        )
        if matched:
            coverage_count[dept] = matched
    return coverage_count, total


